@app.command()
def trades(days: int = typer.Option(30, help="Days of trade history to show")):
    """Show recent trade history."""
    settings = get_settings()
    from finn.database import Database

    db = Database(settings.db_path)
    try:
        recent = db.get_recent_trades(days)
        if not recent:
            console.print("[yellow]No trades yet. Enable trading with FINN_ENABLE_TRADING=true.[/yellow]")
            return

        console.rule("[bold blue]Trade History")
        table = Table()
        table.add_column("Time")
        table.add_column("Mode")
        table.add_column("Side")
        table.add_column("Ticker")
        table.add_column("Amount")
        table.add_column("Conviction")
        table.add_column("Status")

        for t in recent:
            table.add_row(
                t["timestamp"][:16],
                t.get("mode", "?"),
                t.get("side", "?").upper(),
                t["ticker"],
                f"${t.get('notional', 0):.2f}" if t.get("notional") else "?",
                t.get("conviction", "?"),
                t.get("status", "?"),
            )
        console.print(table)
    finally:
        db.close()


@app.command()
def schedule(
    interval_hours: int = typer.Option(24, help="Hours between runs"),
    run_at: str = typer.Option("09:30", help="Time to run daily (HH:MM)"),
):
    """Start the scheduler for automated daily runs."""
    import schedule as sched
    import time
    from finn.main import daily_run

    settings = get_settings()

    console.print(f"[bold]Scheduling Finn to run daily at {run_at}[/bold]")
    console.print("Press Ctrl+C to stop.\n")

    def job():
        try:
            daily_run(settings)
        except Exception as e:
            console.print(f"[red]Run failed: {e}[/red]")

    sched.every().day.at(run_at).do(job)

    # Also run immediately on first start
    console.print("[dim]Running initial cycle now...[/dim]\n")
    job()

    while True:
        sched.run_pending()
        time.sleep(60)


if __name__ == "__main__":
    app()
