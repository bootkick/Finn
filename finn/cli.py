@app.command()
def questions():
    """Show pending questions from Finn."""
    settings = get_settings()
    from finn.human_loop import HumanInTheLoop
    from finn.database import Database

    db = Database(settings.db_path)
    human_loop = HumanInTheLoop(db, settings.data_path)

    pending = human_loop.get_pending_questions()
    if not pending:
        console.print("[green]No pending questions. Finn's got it handled.[/green]")
        db.close()
        return

    console.rule("[bold blue]Finn's Questions")
    for q in pending:
        console.print(f"\n[bold]{q['id']}[/bold] [{q['priority']}]")
        console.print(f"  {q['question']}")
        if q.get("context"):
            console.print(f"  [dim]Context: {q['context']}[/dim]")
        console.print(f"  [dim]Asked: {q['asked_at'][:16]}[/dim]")

    console.print(f"\nAnswer with: [bold]finn answer <question_id> \"your answer\"[/bold]")
    db.close()


@app.command()
def answer(question_id: str, response: str):
    """Answer one of Finn's questions."""
    settings = get_settings()
    from finn.human_loop import HumanInTheLoop
    from finn.database import Database

    db = Database(settings.db_path)
    human_loop = HumanInTheLoop(db, settings.data_path)

    if human_loop.answer(question_id, response):
        console.print(f"[green]Answered {question_id}. Finn will use this in the next evolution cycle.[/green]")
    else:
        console.print(f"[red]Question {question_id} not found.[/red]")
    db.close()


